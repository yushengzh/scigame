RETRYABLE_MINIMAL_CARD_ERROR_CODES = frozenset(
    {
        "minimal_science_card.locator",
        "minimal_science_card.schema",
    }
)


_SYSTEM_PROMPT = """You extract source evidence for a paper-derived scientific benchmark. Return exactly one JSON object matching the supplied schema, with no Markdown or additional text.

Use only the fixed, line-numbered source packet. Do not use outside knowledge and do not infer an omitted coefficient, exponent, range, experimental condition, or uncertainty convention.

Extract at most one relation: the best source-supported executable quantitative relation connecting one to five numeric controls to one or two numeric readouts. A second source-reported condition is not required. Do not construct a pair, alternate world, counterfactual, task prompt, or benchmark design. If the source contains no complete relation, return {\"relations\":[]}.

The relation has exactly six fields: formula, parameters, controls, readouts, domain, and anchors. Formula.outputs is an executable expression tree for the source-reported central relation. Output keys must exactly match the readout names. A var leaf names a declared control and a param leaf names a declared parameter. Every declared control and parameter must occur in the formula. Numeric literals are allowed only for structural zero and one; encode every other scientific constant or fitted value as an anchored parameter. Preserve equality, approximation, fitted-relation, and asymptotic scope through the applicability statements; do not turn proportionality without its coefficient, an inequality, or an unspecified function into an exact point predictor.

A control is a numeric independent variable that can be queried within the source-supported domain. A readout is the quantitative dependent variable returned by the relation. Do not turn a latent quantity or an unreported fitted quantity into a control. Use continuous_interval only when the source supports a finite interval with minimum below maximum. Use numeric_values only for at least two explicitly supported numeric values. The domain must name every control exactly once. Record source-reported applicability or fixed context when present; otherwise use an empty applicability array.

Every formula, parameter value, control definition, readout definition, control domain, and applicability statement must carry direct inclusive source line ranges. Anchors contain line_start and line_end only. Do not generate a paraphrased support field. Use the line coordinates exactly as supplied.

Do not output source identity, schema version, an assessment, readiness flag, mechanisms, claim dependencies, ambiguity records, budget, diagnostic conditions, held-out conditions, public prose, provenance mappings, or code. Source identity and all benchmark-design fields are supplied or generated by deterministic code.
"""


@dataclass(frozen=True)
class MinimalScienceCardResult:
    card: MinimalScienceCard
    response: GenerationResponse
    normalized_source: str
    attempt_count: int


def _source_identity(
    source_citation: str,
    journal_doi: str,
    arxiv_versioned_id: str,
) -> ScienceSource:
    citation = source_citation.strip() if isinstance(source_citation, str) else ""
    if not citation:
        raise ValueError("source_citation must be non-empty text")
    if not isinstance(journal_doi, str):
        raise ValueError("journal_doi must be text")
    doi = canonicalize_doi(journal_doi)
    if doi != journal_doi:
        raise ValueError("journal_doi must use its canonical DOI form")
    return ScienceSource(
        citation=citation,
        journal_doi=doi,
        arxiv_versioned_id=parse_versioned_arxiv_id(arxiv_versioned_id),
    )


def _numbered_source(normalized_source: str) -> str:
    return "\n".join(
        "L%06d\t%s" % (index, line)
        for index, line in enumerate(normalized_source.splitlines(), start=1)
    )


def build_minimal_science_card_request(
    source_text: str,
    *,
    source_citation: str,
    journal_doi: str,
    arxiv_versioned_id: str,
    config: Optional[GenerationConfig] = None,
    source_format: str = "source_packet",
) -> GenerationRequest:
    if source_format not in {"latex", "source_packet"}:
        raise ValueError("source_format must be latex or source_packet")
    normalized = (
        normalize_source_packet(source_text)
        if source_format == "source_packet"
        else normalize_latex(source_text)
    )
    source = _source_identity(
        source_citation,
        journal_doi,
        arxiv_versioned_id,
    )
    schema = minimal_science_card_json_schema()
    system = _SYSTEM_PROMPT + "\nMinimal ScienceCard JSON Schema:\n" + canonical_json_dumps(schema)
    user = (
        "Source metadata for extraction context (do not copy it into the output):\n"
        + json.dumps(
            {
                "arxiv_versioned_id": source.arxiv_versioned_id,
                "citation": source.citation,
                "journal_doi": source.journal_doi,
            },
            ensure_ascii=False,
            sort_keys=True,
        )
        + "\n\nThe line numbers below define the only valid locator coordinate system. File-boundary markers retain source-packet member paths.\n\n"
        + _numbered_source(normalized)
    )
    return GenerationRequest(
        messages=(Message("system", system), Message("user", user)),
        response_schema=schema,
        config=config
        or GenerationConfig(max_output_tokens=32768, temperature=0.0, top_p=1.0),
        metadata={
            "purpose": "temporal_minimal_science_card",
            "source_format": source_format,
        },
    )


def build_minimal_science_card_repair_request(
    primary_request: GenerationRequest,
    previous_output: str,
    validation_error: MinimalScienceCardError,
    *,
    attempt_number: int,
) -> GenerationRequest:
    if primary_request.metadata.get("purpose") != "temporal_minimal_science_card":
        raise ValueError("primary_request must be a minimal ScienceCard request")
    if validation_error.code not in RETRYABLE_MINIMAL_CARD_ERROR_CODES:
        raise ValueError("validation error is not mechanically repairable")
    if (
        isinstance(attempt_number, bool)
        or not isinstance(attempt_number, int)
        or not 2 <= attempt_number <= 4
    ):
        raise ValueError("attempt_number must be between 2 and 4")
    repair = {
        "repair": {
            "instruction": (
                "Return one corrected complete JSON object for the same fixed "
                "source. Change only what is necessary to satisfy the validator "
                "diagnostic. Do not add a scientific fact, relation, value, "
                "domain, or locator. If the rejected relation cannot be made "
                "source-supported, return the structurally valid abstention "
                "{\"relations\":[]}."
            ),
            "previous_output": previous_output,
            "validation_error": {
                "code": validation_error.code,
                "detail": validation_error.detail,
                "path": validation_error.path,
            },
        }
    }
    metadata = dict(primary_request.metadata)
    metadata.update(
        {
            "generation_attempt": attempt_number,
            "repair_reason": validation_error.code,
        }
    )
    return GenerationRequest(
        messages=primary_request.messages
        + (Message("user", canonical_json_dumps(repair)),),
        response_schema=primary_request.response_schema,
        config=primary_request.config,
        metadata=metadata,
    )


def _reject_incomplete(response: GenerationResponse) -> None:
    reason = response.finish_reason.strip().lower()
    if reason in {"length", "max_tokens", "max_output_tokens", "incomplete"} or reason.startswith(
        "incomplete:"
    ):
        raise MinimalScienceCardError(
            "minimal_science_card.incomplete_generation",
            "$",
            "provider generation did not complete (%s)" % response.finish_reason,
        )


def extract_minimal_science_card(
    backend: TextGenerationBackend,
    source_text: str,
    *,
    source_citation: str,
    journal_doi: str,
    arxiv_versioned_id: str,
    config: Optional[GenerationConfig] = None,
    max_total_attempts: int = 1,
    source_format: str = "source_packet",
) -> MinimalScienceCardResult:
    """Extract one minimal card with a frozen proposal-plus-repair budget."""

    if (
        isinstance(max_total_attempts, bool)
        or not isinstance(max_total_attempts, int)
        or not 1 <= max_total_attempts <= 4
    ):
        raise ValueError("max_total_attempts must be an integer between 1 and 4")
    if source_format not in {"latex", "source_packet"}:
        raise ValueError("source_format must be latex or source_packet")
    normalized = (
        normalize_source_packet(source_text)
        if source_format == "source_packet"
        else normalize_latex(source_text)
    )
    source = _source_identity(source_citation, journal_doi, arxiv_versioned_id)
    primary_request = build_minimal_science_card_request(
        source_text,
        source_citation=source.citation,
        journal_doi=source.journal_doi,
        arxiv_versioned_id=source.arxiv_versioned_id,
        config=config,
        source_format=source_format,
    )
    request = primary_request
    source_line_count = len(normalized.splitlines())
    for attempt_count in range(1, max_total_attempts + 1):
        response = backend.generate(request)
        try:
            _reject_incomplete(response)
            card = parse_minimal_science_card_provider_json(
                response.text,
                source=source,
            )
            validate_minimal_science_card_lineage(card, source_line_count)
        except MinimalScienceCardError as error:
            if (
                error.code not in RETRYABLE_MINIMAL_CARD_ERROR_CODES
                or attempt_count >= max_total_attempts
            ):
                raise
            request = build_minimal_science_card_repair_request(
                primary_request,
                response.text,
                error,
                attempt_number=attempt_count + 1,
            )
            continue
        return MinimalScienceCardResult(
            card=card,
            response=response,
            normalized_source=normalized,
            attempt_count=attempt_count,
        )
    raise RuntimeError("unreachable minimal ScienceCard extraction state")


