"""Frozen evaluation methods for matched scientific benchmark families.

The three methods differ only in access to experimental observations.  Their
final submission and case evaluator remain unchanged:

* prior-only baseline: no experimental observation;
* fixed experimental design: receive the pre-specified diagnostic observations;
* adaptive experimental design: experiment without a budget until confidence exceeds the threshold.

Fixed observations are generated by the authoritative case Oracle before the
Player is called.  This keeps experiment selection out of the fixed condition
while retaining an exact, structured record of every supplied observation.
"""

from __future__ import annotations

from dataclasses import dataclass, replace
from typing import Any, Mapping, Optional, Tuple

from .cases.matched import MatchedFamilySpec
from .models import ExperimentProposal, OracleResponse, OracleStatus
from .protocols import BenchmarkCase, CaseOracle
from .wire import (
    canonical_json_dumps,
    experiment_proposal_to_payload,
    oracle_response_to_payload,
)


PRIOR_ONLY_BASELINE = "prior-only baseline"
FIXED_EXPERIMENTAL_DESIGN = "fixed experimental design"
ADAPTIVE_EXPERIMENTAL_DESIGN = "adaptive experimental design"
EVALUATION_METHODS: Tuple[str, ...] = (
    PRIOR_ONLY_BASELINE,
    FIXED_EXPERIMENTAL_DESIGN,
    ADAPTIVE_EXPERIMENTAL_DESIGN,
)
EVALUATION_METHOD_PLAN_SCHEMA = "role_benchmark.evaluation_method_plan.v1"


@dataclass(frozen=True)
class FixedExperiment:
    """One fully specified experiment in a pre-registered fixed design."""

    apparatus: str
    controls: Tuple[Tuple[str, Any], ...]
    readouts: Tuple[str, ...]
    replicates: int = 1

    def proposal(self, index: int, total: int) -> ExperimentProposal:
        return ExperimentProposal(
            intent=(
                "Pre-specified fixed experimental design observation %d of %d."
                % (index, total)
            ),
            apparatus=self.apparatus,
            controls=dict(self.controls),
            readouts=self.readouts,
            replicates=self.replicates,
        )


@dataclass(frozen=True)
class EvaluationMethodPlan:
    """Frozen method assignment and observation budget for one family."""

    family: str
    method: str
    observation_budget: Optional[int]
    fixed_experiments: Tuple[FixedExperiment, ...] = ()

    def __post_init__(self) -> None:
        if self.method not in EVALUATION_METHODS:
            raise ValueError("unknown evaluation method %r" % self.method)
        if self.method == ADAPTIVE_EXPERIMENTAL_DESIGN and self.observation_budget is not None:
            raise ValueError("adaptive design requires an unlimited budget")
        if self.observation_budget is None:
            if self.method != ADAPTIVE_EXPERIMENTAL_DESIGN:
                raise ValueError("only adaptive design permits an unlimited budget")
        elif (
            isinstance(self.observation_budget, bool)
            or not isinstance(self.observation_budget, int)
            or self.observation_budget < 0
        ):
            raise ValueError("observation_budget must be a non-negative integer")
        expected_fixed = (
            self.observation_budget
            if self.method == FIXED_EXPERIMENTAL_DESIGN
            else 0
        )
        if len(self.fixed_experiments) != expected_fixed:
            raise ValueError(
                "fixed experiments must exactly match the fixed-method budget"
            )

    @property
    def require_budget_exhaustion(self) -> bool:
        return self.observation_budget is not None


@dataclass(frozen=True)
class FixedObservation:
    """One authoritative observation supplied under the fixed design."""

    index: int
    proposal: ExperimentProposal
    response: OracleResponse


@dataclass(frozen=True)
class PreparedEvaluationCase:
    """A method-specific public case plus its episode initialization state."""

    case: BenchmarkCase
    plan: EvaluationMethodPlan
    initial_attempts_used: int
    fixed_observations: Tuple[FixedObservation, ...] = ()


def build_evaluation_method_plan(
    spec: MatchedFamilySpec,
    method: str,
    *,
    fixed_budget: Optional[int] = None,
) -> EvaluationMethodPlan:
    """Freeze one method using the family's authored diagnostic conditions.

    The authored diagnostic tuple is already contract-checked to fit the case
    budget, vary its controls, and separate the historical/counterfactual
    mechanisms.  It is therefore the minimal pre-registered design unit used
    here; the runner does not perform result-dependent condition selection.
    """

    if not isinstance(spec, MatchedFamilySpec):
        raise ValueError("spec must be a MatchedFamilySpec")
    if method not in EVALUATION_METHODS:
        raise ValueError(
            "unknown evaluation method %r; choose one of %s"
            % (method, ", ".join(EVALUATION_METHODS))
        )
    experimental_budget = len(spec.diagnostic_conditions)
    if fixed_budget is not None:
        if (method != FIXED_EXPERIMENTAL_DESIGN or isinstance(fixed_budget, bool)
                or not isinstance(fixed_budget, int)
                or not 1 <= fixed_budget <= experimental_budget):
            raise ValueError("fixed_budget must select a positive prefix of the fixed design")
        experimental_budget = fixed_budget
    if method == PRIOR_ONLY_BASELINE:
        return EvaluationMethodPlan(
            family=spec.family,
            method=method,
            observation_budget=0,
        )
    if method == ADAPTIVE_EXPERIMENTAL_DESIGN:
        return EvaluationMethodPlan(
            family=spec.family,
            method=method,
            observation_budget=None,
        )
    control_names = tuple(control.name for control in spec.controls)
    experiments = tuple(
        FixedExperiment(
            apparatus=spec.apparatus_name,
            controls=tuple((name, condition[name]) for name in control_names),
            readouts=tuple(readout.name for readout in spec.readouts),
            replicates=1,
        )
        for condition in spec.diagnostic_conditions[:experimental_budget]
    )
    return EvaluationMethodPlan(
        family=spec.family,
        method=method,
        observation_budget=experimental_budget,
        fixed_experiments=experiments,
    )


def evaluation_method_plan_to_payload(
    plan: EvaluationMethodPlan,
) -> Mapping[str, Any]:
    return {
        "schema": EVALUATION_METHOD_PLAN_SCHEMA,
        "family": plan.family,
        "evaluation_method": plan.method,
        "observation_budget": plan.observation_budget,
        "fixed_experiments": [
            {
                "apparatus": experiment.apparatus,
                "controls": dict(experiment.controls),
                "readouts": list(experiment.readouts),
                "replicates": experiment.replicates,
            }
            for experiment in plan.fixed_experiments
        ],
    }


def fixed_observation_to_payload(
    observation: FixedObservation,
) -> Mapping[str, Any]:
    return {
        "observation_index": observation.index,
        "proposal": experiment_proposal_to_payload(observation.proposal),
        "response": oracle_response_to_payload(observation.response),
    }


def _method_note(plan: EvaluationMethodPlan) -> str:
    if plan.method == PRIOR_ONLY_BASELINE:
        return (
            "Evaluation method: prior-only baseline. No experimental observation "
            "is available. Do not propose an experiment; submit the final "
            "predictor immediately."
        )
    if plan.method == FIXED_EXPERIMENTAL_DESIGN:
        return (
            "Evaluation method: fixed experimental design. The benchmark service "
            "has already supplied exactly %d pre-specified observations below. "
            "The Player cannot choose or request more experiments and must now "
            "submit the final predictor." % plan.observation_budget
        )
    return (
        "Evaluation method: adaptive experimental design. There is no experiment "
        "budget or action-count limit. budget=null and attempts_remaining=null "
        "mean unlimited, not zero. Continue choosing experiments until the "
        "confidence in your selected hypothesis strictly exceeds the public "
        "confidence_threshold. As soon as this happens, submit its executable "
        "final predictor rather than requesting additional experiments. You may "
        "submit without experiments if your initial confidence already exceeds "
        "the threshold. All non-clarification experiment attempts are recorded. "
        "Confidence determines when to stop, not whether the prediction is correct."
    )


def prepare_evaluation_case(
    case: BenchmarkCase,
    spec: MatchedFamilySpec,
    method: str,
    *,
    fixed_budget: Optional[int] = None,
    count_all_experiment_attempts: bool = False,
) -> PreparedEvaluationCase:
    """Prepare one case without changing its final evaluator or private world."""

    plan = build_evaluation_method_plan(spec, method, fixed_budget=fixed_budget)
    if (plan.observation_budget is not None and case.definition.budget is not None
            and plan.observation_budget > case.definition.budget):
        raise ValueError(
            "evaluation-method observation budget exceeds the case budget"
        )

    observations = ()
    supplied_observations = ()
    initial_attempts_used = 0
    if method == FIXED_EXPERIMENTAL_DESIGN:
        oracle = CaseOracle(case.definition, case.world_model)
        collected = []
        rendered = []
        for index, experiment in enumerate(plan.fixed_experiments, start=1):
            proposal = experiment.proposal(index, plan.observation_budget)
            response = oracle.respond(proposal)
            if response.status is not OracleStatus.VALID:
                raise ValueError(
                    "pre-specified fixed experiment %d is not valid" % index
                )
            observation = FixedObservation(index, proposal, response)
            collected.append(observation)
            rendered.append(
                "Fixed experimental design observation %d/%d: %s"
                % (
                    index,
                    plan.observation_budget,
                    canonical_json_dumps(fixed_observation_to_payload(observation)),
                )
            )
        observations = tuple(collected)
        supplied_observations = tuple(rendered)
        initial_attempts_used = plan.observation_budget

    method_note = _method_note(plan)
    if count_all_experiment_attempts:
        method_note = method_note.replace(
            "All non-clarification experiment attempts are recorded.",
            "Every experiment request sent to the Oracle counts as one attempt, "
            "including rejected requests and requests needing clarification.",
        )
    resources = replace(
        case.definition.resources,
        notes=case.definition.resources.notes + (method_note,),
    )
    definition = replace(
        case.definition,
        count_all_experiment_attempts=count_all_experiment_attempts,
        budget=None if method == ADAPTIVE_EXPERIMENTAL_DESIGN else case.definition.budget,
        initial_observations=(
            case.definition.initial_observations + supplied_observations
        ),
        resources=resources,
    )
    prepared_case = BenchmarkCase(definition, case.world_model, case.evaluator)
    return PreparedEvaluationCase(
        case=prepared_case,
        plan=plan,
        initial_attempts_used=initial_attempts_used,
        fixed_observations=observations,
    )


